        // 這會導致一個你在遊戲中很熟悉的視覺效果：太靠近一個物體的時候你的視線會直接穿過。 
    
    // 當使用正射投影時，每個頂點座標都會直接映射到裁剪空間中而不經過任何精細的透視除法（它仍然會進行透視除法，只是w分量沒有被改變（它保持為1），因此沒有起作用）。
    // 因為正射投影沒有使用透視，遠處的物體不會顯得更小，所以產生奇怪的視覺效果。由於這個原因，正射投影主要用於二維渲染以及一些建築或工程的程序，
    // 在這些場景中我們更希望頂點不會被透視所干擾。某些如Blender等進行三維建模的軟體有時在建模時也會使用正射投影，因為它在各個維度下都更準確地描繪了每個物體。
    // 下面你能夠看到在Blender裡面使用兩種投影方式的對比：
    // https://learnopengl.com/img/getting-started/perspective_orthographic.png
    // 你可以看到，使用透視投影的話，遠處的頂點看起來比較小，而在正射投影中每個頂點距離觀察者的距離都是一樣的。



    // --------------------<把它們都組合在一起>--------------------
    // 我們為上述的每一個步驟都創建了一個變換矩陣：模型矩陣、觀察矩陣和投影矩陣。一個頂點座標將會根據以下過程被變換到裁剪座標：
    // Vclip=Mprojection ⋅ Mview ⋅ Mmodel ⋅ Vlocal
    // 注意矩陣運算的順序是相反的（記住我們需要從右往左閱讀矩陣的乘法）。最後的頂點應該被賦值到頂點著色器中的gl_Position，OpenGL將會自動進行透視除法和裁切。
        // 然後呢？
        // 頂點著色器的輸出要求所有的頂點都在裁剪空間內，而這正是我們剛才使用變換矩陣所做的。 OpenGL然後對裁剪座標執行透視除法從而將它們變換到標準化設備座標。 
        // OpenGL會使用glViewPort內部的參數來將標準化設備座標映射到螢幕座標，每個座標都關聯了一個螢幕上的點（在我們的例子中是一個800x600的螢幕）。
        // 這個過程稱為視窗變換。
    // 這一章的主題可能會比較難理解，如果你仍然不確定每個空間的作用的話，你也不必太擔心。接下來你會看到我們是怎麼運用這些座標空間的，而且之後也會有足夠的例子。









    // --------------------<進入3D>--------------------
    // 既然我們知道如何將3D座標變換為2D座標，我們可以開始使用真正的3D物體，而不是枯燥的2D平面了。
    // 在開始進行3D繪圖時，我們先建立一個模型矩陣。這個模型矩陣包含了位移、縮放與旋轉操作，它們會被應用到所有物體的頂點上，以變換它們到全局的世界空間。
    // 讓我們變換一下我們的平面，將其繞著x軸旋轉，使它看起來像放在地上一樣。這個模型矩陣看起來是這樣的：
    glm::mat4 model;
    model = glm::rotate(model, glm::radians(-55.0f), glm::vec3(1.0f, 0.0f, 0.0f));
    // 透過將頂點座標乘以這個模型矩陣，我們將該頂點座標變換到世界座標。我們的平面看起來就是在地板上，代表全局世界裡的平面
    // 接下來我們需要建立一個觀察矩陣。我們想要在場景裡面稍微往後移動，以使得物體變成可見的（當在世界空間時，我們位於原點(0,0,0)）。
    // 想要在場景裡面移動，先仔細想想下面這個句子：
        // 將攝影機向後移動，和將整個場景向前移動是一樣的。
    // 這正是觀察矩陣所做的，我們以相反於攝影機移動的方向移動整個場景。因為我們想要往後移動，而OpenGL是一個右手座標系(Right-handed System)，
    // 所以我們需要沿著z軸的正方向移動。我們會透過將場景沿著z軸負方向平移來實現。它會給我們一種我們在往後移動的感覺。

        // 右手座標系(Right-handed System)
        // 按照慣例，OpenGL是一個右手座標系。簡單來說，就是正x軸在你的右手邊，正y軸朝上，而正z軸是朝向後方的。
        // 想像你的螢幕處於三個軸的中心，則正z軸穿過你的螢幕朝向你。坐標系畫起來如下：
        // https://learnopengl.com/img/getting-started/coordinate_systems_right_handed.png

        // 為了理解為什麼被稱為右手座標系，如下的步驟做：
            // 沿著正y軸方向伸出你的右臂，手指著上方。
            // 大拇指指向右方。
            // 食指指向上方。
            // 中指向下彎曲90度。
        // 如果你的動作正確，那麼你的大拇指指向正x軸方向，食指指向正y軸方向，中指指向正z軸方向。如果你用左手臂來做這些動作，你會發現z軸的方向是相反的。
        // 這個叫做左手座標系，它被DirectX廣泛使用。注意在標準化設備座標系中OpenGL實際上使用的是左手座標系（投影矩陣交換了左右手）。

    // 在下一個教學中我們將會詳細討論如何在場景中移動。就目前來說，觀察矩陣是這樣的：
    glm::mat4 view;
    // 注意，我們將矩陣往我們要進行移動場景的反方向移動。
    view = glm::translate(view, glm::vec3(0.0f, 0.0f, -3.0f));
    
    // 最後我們要做的是定義一個投影矩陣。我們希望在場景中使用透視投影，所以像這樣聲明一個投影矩陣：
    glm::mat4 projection;
    projection = glm::perspective(glm::radians(45.0f), screenWidth / screenHeight, 0.1f, 100.0f);

    // 既然我們已經創建了變換矩陣，我們應該將它們傳入著色器。首先，讓我們在頂點著色器中聲明一個uniform變換矩陣然後將它乘以頂點座標：
        // #version 330 core
        // layout (location = 0) in vec3 aPos;
        // …
        // uniform mat4 model;
        // uniform mat4 view;
        // uniform mat4 projection;

        // void main()
        // {
        //  // 注意乘法要從右向左讀
        //  gl_Position = projection * view * model * vec4(aPos, 1.0);
        //  …
        // }
    // 我們還應該將矩陣傳入著色器（這通常在每次的渲染迭代中進行，因為變換矩陣會經常變動）：
    int modelLoc = glGetUniformLocation(ourShader.ID, "model");
    glUniformMatrix4fv(modelLoc, 1, GL_FALSE, glm::value_ptr(model));
    //... // 觀察矩陣與投影矩陣與之類似

    // 我們的頂點座標已經使用模型、觀察和投影矩陣進行變換了，最終的物體應該會：
        // 稍微向後傾斜至地板方向。
        // 離我們有一些距離。
        // 有透視效果（頂點越遠，變得越小）。
        // 讓我們檢查一下結果是否符合這些要求：


    // --------------------<更加3D>--------------------
    // 到目前為止，我們一直都在使用一個2D平面，而且甚至在3D空間裡！所以，讓我們大膽地拓展我們的2D平面為一個3D立方體。
    // 要渲染一個立方體，我們一共需要36個頂點（6個面x 每個面有2個三角形組成x 每個三角形有3個頂點），這36個頂點的位置你可以從這裡取得。
    // https://learnopengl.com/code_viewer.php?code=getting-started/cube_vertices

    // 為了有趣一點，我們將讓立方體隨著時間旋轉：
    model = glm::rotate(model, (float)glfwGetTime() * glm::radians(50.0f), glm::vec3(0.5f, 1.0f, 0.0f));
    // 然後我們使用glDrawArrays來繪製立方體，但這次總共有36個頂點。
    glDrawArrays(GL_TRIANGLES, 0, 36);
