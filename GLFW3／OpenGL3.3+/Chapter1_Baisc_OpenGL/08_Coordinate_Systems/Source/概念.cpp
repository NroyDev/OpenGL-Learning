    // 這的確有點像是個立方體，但又有種說不出的奇怪。立方體的某些本應被遮擋住的面被繪製在了這個立方體其他面之上。
    // 之所以這樣是因為OpenGL是一個三角形一個三角形地來繪製你的立方體的，所以即便之前那裡有東西它也會覆蓋之前的像素。
    // 因為這個原因，有些三角形會被繪製在其它三角形上面，雖然它們本來不應該是被覆蓋的。

