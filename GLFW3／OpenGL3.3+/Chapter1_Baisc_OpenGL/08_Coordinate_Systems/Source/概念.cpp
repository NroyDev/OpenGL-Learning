    // 因為我們使用了深度測試，我們也想要在每次渲染迭代之前清除深度緩衝（否則前一幀的深度資訊仍然保存在緩衝中）。
    // 就像清除顏色緩衝一樣，我們可以透過在glClear函數中指定DEPTH_BUFFER_BIT位元來清除深度緩衝：
    glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);

    // 讓我們來重新執行一下程式看看OpenGL是否執行了深度測試
    // ... 就是這樣！一個開啟了深度測試，各個面都是紋理，而且還在旋轉的立方體！


    // --------------------<更多的立方體！>--------------------
    // 現在我們想在螢幕上顯示10個立方體。每個立方體看起來都是一樣的，差別在於它們在世界的位置及旋轉角度不同。
    // 立方體的圖形佈局已經定義好了，所以當渲染更多物體的時候我們不需要改變我們的緩衝數組和屬性數組，
    // 我們唯一需要做的只是改變每個對象的模型矩陣來將立方體變換到世界坐標系中。
    // 首先，讓我們為每個立方體定義一個位移向量來指定它在世界空間的位置。我們將在一個glm::vec3陣列中定義10個立方體位置：
    glm::vec3 cubePositions[] = {
        glm::vec3( 0.0f,  0.0f,  0.0f), 
        glm::vec3( 2.0f,  5.0f, -15.0f), 
        glm::vec3(-1.5f, -2.2f, -2.5f),  
        glm::vec3(-3.8f, -2.0f, -12.3f),  
        glm::vec3( 2.4f, -0.4f, -3.5f),  
        glm::vec3(-1.7f,  3.0f, -7.5f),  
        glm::vec3( 1.3f, -2.0f, -2.5f),  
        glm::vec3( 1.5f,  2.0f, -2.5f), 
        glm::vec3( 1.5f,  0.2f, -1.5f), 
        glm::vec3(-1.3f,  1.0f, -1.5f)  
    };

    // 現在，在遊戲循環中，我們調用glDrawArrays10次​​，但這次在我們渲染之前每次傳入一個不同的模型矩陣到頂點著色器。
    // 我們將會在遊戲循環中創建一個小的循環用不同的模型矩陣渲染我們的物件10次。注意我們也對每個箱子加了一點旋轉：
    glBindVertexArray(VAO);
    for(unsigned int i = 0; i < 10; i++){
        glm::mat4 model;
        model = glm::translate(model, cubePositions[i]);
        float angle = 20.0f * i; 
        model = glm::rotate(model, glm::radians(angle), glm::vec3(1.0f, 0.3f, 0.5f));
        ourShader.setMat4("model", model);

        glDrawArrays(GL_TRIANGLES, 0, 36);
    }
    // 這段程式碼將會在每次新立方體繪製出來的時候更新模型矩陣，如此總共重複10次。然後我們應該就能看到一個擁有10個正在奇葩地旋轉著的立方體的世界。
    

