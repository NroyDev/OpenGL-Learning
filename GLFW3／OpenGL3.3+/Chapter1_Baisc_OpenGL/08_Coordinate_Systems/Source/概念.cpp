    // 透過使用Z緩衝，我們可以設定OpenGL來進行深度測試。

    // --------------------<Z緩衝>--------------------
    // OpenGL儲存它的所有深度資訊於一個Z緩衝(Z-buffer)中，也被稱為深度緩衝(Depth Buffer)。 
    // GLFW會自動為你產生這樣一個緩衝（就像它也有一個顏色緩衝來儲存輸出影像的顏色）。深度值儲存在每個片段裡面（作為片段的z值），當片段想要輸出它的顏色時，
    // OpenGL會將它的深度值和z緩衝進行比較，如果當前的片段在其它片段之後，它將會被丟棄，否則將會覆蓋。這個過程稱為深度測試(Depth Testing)，它是由OpenGL自動完成的。

    // 然而，如果我們想要確定OpenGL真的執行了深度測試，首先我們要告訴OpenGL我們想要啟用深度測試；它預設是關閉的。我們可以透過glEnable函數來開啟深度測試。
    // glEnable和glDisable函數允許我們啟用或停用某個OpenGL功能。這個功能會一直保持啟用/停用狀態，直到另一個呼叫來停用/啟用它。
    // 現在我們要啟用深度測試，需要開啟GL_DEPTH_TEST：
