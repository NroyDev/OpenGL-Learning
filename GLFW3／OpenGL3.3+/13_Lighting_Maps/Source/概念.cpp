        // vec3 ambient = light.ambient * vec3(texture(material.diffuse, TexCoords));

    // 這就是使用漫反射貼圖的全部步驟了。你可以看到，這並不是什麼新的東西，但這能夠大大提高視覺品質。為了讓它正常工作，我們還需要使用紋理座標更新頂點數據，
